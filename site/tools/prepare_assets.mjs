/**
 * Build-time-only asset preparation. Run locally, commit the output.
 *
 *   cd site/tools && npm install && npm run prepare-assets
 *
 * Reads the authored masters that ship with the source package and writes
 * derivatives the dependency-free Python build simply copies:
 *
 *   src/fonts.source.css  ->  src/fonts.css + src/fonts/*.woff2
 *   src/assets/*          ->  src/derivatives/* + src/derivatives.json
 *   (brand marks)         ->  src/static/* (favicons, social image)
 *
 * Masters are never modified. Composition, framing and declared dimensions
 * are preserved; only the encoding and pixel ladder change.
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync, statSync, copyFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { compress } from 'wawoff2';

const HERE = dirname(fileURLToPath(import.meta.url));
const SITE = join(HERE, '..');
const SRC = join(SITE, 'src');

const kb = (n) => (n / 1024).toFixed(1) + ' KB';
const size = (p) => statSync(p).size;

/* ------------------------------------------------------------------ fonts */

// Exact families and weights as authored. Only the container format changes.
const FONT_FILES = {
  'DM Sans|normal|300': 'DMSans-300',
  'DM Sans|normal|400': 'DMSans-400',
  'DM Sans|normal|500': 'DMSans-500',
  'Instrument Serif|normal|400': 'InstrumentSerif-400',
  'Instrument Serif|italic|400': 'InstrumentSerif-400-italic',
};

async function fonts() {
  const source = readFileSync(join(SRC, 'fonts.source.css'), 'utf8');
  const blocks = source.match(/@font-face\s*\{[^}]*\}/g) || [];
  if (!blocks.length) throw new Error('No @font-face blocks found in fonts.source.css');

  mkdirSync(join(SRC, 'fonts'), { recursive: true });
  const out = [];
  let before = 0, after = 0;

  for (const block of blocks) {
    const pick = (prop) => (block.match(new RegExp(prop + ':\\s*([^;]+);')) || [])[1]?.trim();
    const family = pick('font-family').replace(/['"]/g, '');
    const style = pick('font-style');
    const weight = pick('font-weight');
    const display = pick('font-display') || 'swap';
    const b64 = (block.match(/src:\s*url\(data:font\/[a-z0-9-]+;base64,([A-Za-z0-9+/=]+)\)/) || [])[1];
    if (!b64) throw new Error(`No embedded font data for ${family} ${style} ${weight}`);

    const key = `${family}|${style}|${weight}`;
    const name = FONT_FILES[key];
    if (!name) throw new Error(`Unmapped face: ${key}`);

    const ttf = Buffer.from(b64, 'base64');
    const woff2 = Buffer.from(await compress(ttf));
    writeFileSync(join(SRC, 'fonts', name + '.woff2'), woff2);

    before += Buffer.byteLength(b64, 'utf8'); // bytes actually shipped before
    after += woff2.length;
    console.log(`  font ${name.padEnd(28)} ttf ${kb(ttf.length).padStart(10)} -> woff2 ${kb(woff2.length).padStart(9)} (base64 in CSS was ${kb(Buffer.byteLength(b64, 'utf8'))})`);

    out.push(
      `@font-face {\n  font-family: '${family}';\n  font-style: ${style};\n  font-weight: ${weight};\n` +
      `  font-display: ${display};\n  src: url(fonts/${name}.woff2) format('woff2');\n}`
    );
  }

  writeFileSync(join(SRC, 'fonts.css'), '/* Generated by tools/prepare_assets.mjs from fonts.source.css. Do not edit. */\n' + out.join('\n') + '\n');
  return { before, after, faces: blocks.length };
}

/* ----------------------------------------------------------------- images */

// Painted width the browser actually needs — not the box width. `object-fit:
// cover` paints wider than its box and `contain` paints narrower, and the page
// container is fluid (--page-width:1480px, --edge:clamp(24px,4.2vw,76px)).
// These were measured in Chrome at 390/420/600/768/1000/1200/1440/1800px and
// are set a few percent generous so no breakpoint upscales.
const SIZES = {
  'advisors-hero': '(max-width:760px) 112vw, (max-width:1100px) 58vw, (max-width:1300px) 800px, 900px',
  'advisor-community': '(max-width:760px) 103vw, (max-width:1500px) 92vw, 1330px',
  'advisor-walking': '(max-width:760px) min(88vw, 490px), (max-width:1600px) 34vw, 490px',
  'keir-current': '(max-width:760px) min(82vw, 380px), (max-width:1600px) 32vw, 470px',
  'frends-product': '(max-width:420px) 185px, (max-width:760px) 140px, 250px',
  'open-cans': '(max-width:420px) 82vw, (max-width:1350px) 40vw, 530px',
};

const LADDER = [480, 720, 960, 1200];
const AVIF = { quality: 68, effort: 6, chromaSubsampling: '4:4:4' };
const WEBP = { quality: 84, effort: 6 };

async function images() {
  const assets = JSON.parse(readFileSync(join(SRC, 'assets.json'), 'utf8'));
  const dest = join(SRC, 'derivatives');
  rmSync(dest, { recursive: true, force: true });
  mkdirSync(dest, { recursive: true });

  const manifest = {};
  const report = [];

  for (const [key, a] of Object.entries(assets)) {
    const master = join(SRC, 'assets', a.file);
    const masterBytes = size(master);
    const stem = a.file.replace(/\.[^.]+$/, '');
    const widths = [...new Set(LADDER.filter((w) => w < a.width).concat(a.width))].sort((x, y) => x - y);
    const meta = await sharp(master).metadata();
    const hasAlpha = Boolean(meta.hasAlpha);

    const entry = { avif: [], webp: [], width: a.width, height: a.height, sizes: SIZES[key] };
    let avifTotal = 0, webpTotal = 0;

    for (const w of widths) {
      const base = sharp(master).resize({ width: w, withoutEnlargement: true, kernel: 'lanczos3' });
      const avifName = `${stem}-${w}.avif`;
      const webpName = `${stem}-${w}.webp`;
      await base.clone().avif(AVIF).toFile(join(dest, avifName));
      await base.clone().webp({ ...WEBP, alphaQuality: 100 }).toFile(join(dest, webpName));
      entry.avif.push([avifName, w]);
      entry.webp.push([webpName, w]);
      avifTotal += size(join(dest, avifName));
      webpTotal += size(join(dest, webpName));
    }

    // Fallback for the handful of browsers without WebP. Keeps the original
    // container semantics: PNG where alpha is used, JPEG for opaque photos.
    // No palette quantisation — the alpha master is a smooth product render.
    const fbWidth = Math.min(hasAlpha ? 720 : 960, a.width);
    let fallbackName = hasAlpha ? `${stem}-${fbWidth}.png` : `${stem}-${fbWidth}.jpg`;
    const fb = sharp(master).resize({ width: fbWidth, withoutEnlargement: true, kernel: 'lanczos3' });
    if (hasAlpha) await fb.png({ compressionLevel: 9, effort: 10 }).toFile(join(dest, fallbackName));
    else await fb.jpeg({ quality: 82, mozjpeg: true, chromaSubsampling: '4:4:4' }).toFile(join(dest, fallbackName));

    // A derivative that beats nothing is not worth shipping: keep the master.
    if (size(join(dest, fallbackName)) >= masterBytes) {
      rmSync(join(dest, fallbackName));
      fallbackName = a.file;
      copyFileSync(master, join(dest, fallbackName));
    }
    entry.fallback = fallbackName;

    const fbBytes = size(join(dest, fallbackName));
    // What a real visit costs: one AVIF at the largest ladder step, vs the master.
    const largestAvif = size(join(dest, entry.avif[entry.avif.length - 1][0]));
    report.push({ key, file: a.file, master: masterBytes, avifLargest: largestAvif, fallback: fbBytes, avifTotal, webpTotal, widths });
    manifest[key] = entry;

    console.log(`  image ${key.padEnd(19)} master ${kb(masterBytes).padStart(11)} -> avif@${String(widths.at(-1)).padStart(4)} ${kb(largestAvif).padStart(9)}  fallback ${kb(fbBytes).padStart(9)}  [${widths.join(', ')}]`);
  }

  writeFileSync(join(SRC, 'derivatives.json'), JSON.stringify(manifest, null, 2) + '\n');
  return report;
}

/* -------------------------------------------------------- brand and social */

const PAPER = '#FAF8F4', INK = '#1E1D1A', WALNUT = '#A07850', ORANGE = '#D4663A';

async function branding() {
  const dest = join(SRC, 'static');
  mkdirSync(dest, { recursive: true });

  // src/static/assets/images/ holds the brand marks the previous site published.
  // They stay at their original public paths so external references keep working.
  const legacy = join(dest, 'assets', 'images');
  mkdirSync(legacy, { recursive: true });

  // Favicon: the established cognac disc, redrawn with the current wordmark
  // initial. Same mark family the existing site shipped as a data URI.
  const mark = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <rect width="64" height="64" fill="${WALNUT}"/>
  <path d="M0 58h64v6H0z" fill="${ORANGE}"/>
  <text x="32" y="45" text-anchor="middle" font-family="Georgia, 'Times New Roman', serif" font-size="42" fill="${PAPER}">D</text>
</svg>`;
  writeFileSync(join(dest, 'favicon.svg'), mark);
  await sharp(Buffer.from(mark)).resize(180, 180).png().toFile(join(dest, 'apple-touch-icon.png'));
  await sharp(Buffer.from(mark)).resize(32, 32).png().toFile(join(dest, 'favicon-32.png'));

  // Social sharing image: brand system only — wordmark, descriptor, palette.
  // No claim, metric, client name or testimonial appears on it.
  const wordmark = readFileSync(join(legacy, 'dillon-logo-agency-cognac.svg'), 'utf8')
    .replace(/fill:\s*#8C6840/gi, `fill: ${INK}`);
  const wordmarkPng = await sharp(Buffer.from(wordmark)).resize({ width: 760 }).png().toBuffer();

  const card = `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630">
  <rect width="1200" height="630" fill="${PAPER}"/>
  <rect x="0" y="0" width="1200" height="14" fill="${WALNUT}"/>
  <rect x="0" y="616" width="1200" height="14" fill="${WALNUT}"/>
  <rect x="96" y="392" width="96" height="4" fill="${ORANGE}"/>
  <text x="96" y="452" font-family="Georgia, 'Times New Roman', serif" font-size="40" fill="${INK}">Marketing leadership for</text>
  <text x="96" y="502" font-family="Georgia, 'Times New Roman', serif" font-size="40" fill="${INK}">wealth management firms</text>
  <text x="96" y="556" font-family="Helvetica, Arial, sans-serif" font-size="22" fill="#6B6862">Led by Keir Dillon · dillonagency.co</text>
</svg>`;
  await sharp(Buffer.from(card))
    .composite([{ input: wordmarkPng, left: 96, top: 150 }])
    .png()
    .toFile(join(dest, 'social-card.png'));

  console.log(`  brand  favicon.svg, favicon-32.png, apple-touch-icon.png, social-card.png (${kb(size(join(dest, 'social-card.png')))})`);
}

/* -------------------------------------------------------------------- run */

console.log('Fonts');
const f = await fonts();
console.log('\nImages');
const imgs = await images();
console.log('\nBranding');
await branding();

const masterTotal = imgs.reduce((s, r) => s + r.master, 0);
const servedTotal = imgs.reduce((s, r) => s + r.avifLargest, 0);
console.log('\nSummary');
console.log(`  fonts   ${f.faces} faces: ${kb(f.before)} of base64 in CSS -> ${kb(f.after)} of WOFF2`);
console.log(`  images  ${imgs.length} masters: ${kb(masterTotal)} -> ${kb(servedTotal)} at the largest AVIF step`);

writeFileSync(join(SITE, 'asset-report.json'), JSON.stringify({
  generated: new Date().toISOString().slice(0, 10),
  fonts: { faces: f.faces, base64_in_css_bytes: f.before, woff2_bytes: f.after },
  images: imgs,
}, null, 2) + '\n');
